# Entry points
# ---------------------------------------------------------------------------


def load_catalog(bundles_dir: Path = BUNDLES_DIR) -> Catalog:
    catalog = from_roots([bundles_dir / "packs"], [bundles_dir])
    if catalog.problems:
        raise SystemExit("manifest problems; run `archi bundles validate`:\n" + "\n".join(str(p) for p in catalog.problems))
    return catalog


def generate(bundles_dir: Path = BUNDLES_DIR) -> dict[str, str]:
    """Page path (relative to docs/docs/) -> text, for every generated page."""
    catalog = load_catalog(bundles_dir)
    pages = {f"{CATALOG_DIR}/index.md": _index_page(catalog), CLI_PAGE: cli_page()}
    for name, bundle in catalog.bundles.items():
        pages[f"{CATALOG_DIR}/bundles/{name}.md"] = bundle_page(bundle, catalog)
    for name, pack in catalog.packs.items():
        pages[f"{CATALOG_DIR}/packs/{name}.md"] = pack_page(pack, catalog)
    return dict(sorted(pages.items()))


def stale(docs_dir: Path = DOCS_DIR, bundles_dir: Path = BUNDLES_DIR) -> list[str]:
    """Problems between the committed pages and a fresh render (empty when current)."""
    pages = generate(bundles_dir)
    problems = []
    for rel, text in pages.items():
        path = docs_dir / rel
        if not path.is_file():
            problems.append(f"missing: {rel}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"stale: {rel}")
    catalog_dir = docs_dir / CATALOG_DIR
    if catalog_dir.is_dir():
        for path in sorted(catalog_dir.rglob("*.md")):
            rel = path.relative_to(docs_dir).as_posix()
            if rel not in pages:
                problems.append(f"orphan: {rel}")
    return problems


def write(docs_dir: Path = DOCS_DIR, bundles_dir: Path = BUNDLES_DIR) -> list[str]:
    pages = generate(bundles_dir)
    catalog_dir = docs_dir / CATALOG_DIR
    for path in sorted(catalog_dir.rglob("*.md")) if catalog_dir.is_dir() else []:
        if path.relative_to(docs_dir).as_posix() not in pages:
            path.unlink()
    for rel, text in pages.items():
        path = docs_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return list(pages)


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m archi.docs_gen", description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a committed page is stale")
    args = ap.parse_args(argv)
    if args.check:
        problems = stale()
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    print(f"wrote {len(write())} pages under {DOCS_DIR.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
