def _walk_parser(parser: argparse.ArgumentParser, prog: str, out: list[str], level: int) -> None:
    positionals, options, subs = [], [], None
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            subs = action
        elif isinstance(action, argparse._HelpAction):
            continue
        elif action.option_strings:
            options.append(action)
        else:
            positionals.append(action)

    if positionals:
        out += _table(
            ["Argument", "Meaning"],
            [[_code(a.metavar or a.dest), _cell(a.help or "")] for a in positionals],
        )
    if options:
        rows = []
        for a in options:
            flags = ", ".join(a.option_strings)
            if a.nargs != 0:
                flags += " " + (a.metavar or a.dest.upper())
            default = ""
            if isinstance(a.default, (str, int, float, Path)) and not isinstance(a.default, bool) and a.default != argparse.SUPPRESS:
                default = _code(a.default)
            rows.append([_code(flags), _cell(a.help or ""), default])
        out += _table(["Option", "Meaning", "Default"], rows)
    if subs is not None:
        helps = {ca.dest: ca.help for ca in subs._choices_actions}
        for name, sub in subs.choices.items():
            out += [f"{'#' * level} `{prog} {name}`", ""]
            if helps.get(name):
                text = _one_line(helps[name])
                out += [text[0].upper() + text[1:] + ("" if text.endswith(".") else "."), ""]
            _walk_parser(sub, f"{prog} {name}", out, level + 1)


def cli_page() -> str:
    from archi.bundles.cli import build_parser

    parser = build_parser(load_ops=True)
    out = [
        BANNER.format(source="the argparse parser in archi.bundles.cli"),
        "# Command reference",
        "",
        "Every `archi` command, as its parser defines it. Run `archi <command> --help` for the same text in a terminal.",
        "",
        "Commands that read an instance take `--instance DIR` (default: the current directory).",
        "",
    ]
    _walk_parser(parser, "archi", out, 2)
    return "\n".join(out).rstrip() + "\n"


