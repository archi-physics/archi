"""Generate the docs pages that must not drift from the code (PACT r3-docs).

One page per bundle and per pack, rendered from `bundle.yaml` / `pack.yaml`
and the files they name, plus the CLI reference, rendered from the argparse
parser. The output goes under `docs/docs/` and is committed;
`python/tests/test_docs_generated.py` fails when a committed page differs
from what this module produces, so a manifest change without a regenerated
page cannot merge.

    cd python && python -m archi.docs_gen            # rewrite the pages
    cd python && python -m archi.docs_gen --check    # exit 1 if any is stale

Why a module in the package, not a script under `scripts/`: the test imports
it directly, and it uses the same loaders as `archi bundles validate`, so it
cannot read a manifest differently from the CLI. Why committed output, not a
mkdocs hook: the docs deploy job installs only mkdocs, not archi and okg, and
a committed page can be reviewed in the diff.

Only the repository's own `bundles/` tree is read, never installed
third-party packs, so the output is the same on every machine. Nothing here
writes a date, a path outside the repo, or anything read from the environment.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Iterable, Mapping, Optional

from archi.bundles.discovery import Catalog, from_roots
from archi.bundles.manifest import Bundle, Pack, load_unique_yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCS_DIR = REPO_ROOT / "docs" / "docs"
BUNDLES_DIR = REPO_ROOT / "bundles"

#: Generated page locations, relative to the docs directory.
CATALOG_DIR = "library"
CLI_PAGE = "reference/cli.md"

GITHUB = "https://github.com/archi-physics/archi/blob/archi_v3"

BANNER = (
    "<!-- Generated by python/archi/docs_gen.py from {source}. Do not edit by hand: "
    "run `cd python && python -m archi.docs_gen`. -->\n"
)


# ---------------------------------------------------------------------------
# Small formatting helpers
# ---------------------------------------------------------------------------


def _one_line(text: Any) -> str:
    """Collapse whitespace so a folded YAML string reads as one line."""
    return " ".join(str(text).split())


def _cell(text: Any) -> str:
    """A value safe inside a Markdown table cell."""
    return re.sub(r"(?<!\\)\|", r"\\|", _one_line(text)).replace("<", "&lt;").replace(">", "&gt;")


def _code(value: Any) -> str:
    text = _one_line(value)
    return f"`{text}`" if text else ""


def _table(header: list[str], rows: Iterable[list[str]]) -> list[str]:
    rows = list(rows)
    if not rows:
        return []
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(_cell(c) if not c.startswith("`") else c for c in row) + " |" for row in rows]
    return out + [""]


def _pack_link(name: str, known: Mapping[str, Pack]) -> str:
    return f"[`{name}`](../packs/{name}.md)" if name in known else f"`{name}`"


def _list_inline(names: Iterable[str], known: Mapping[str, Pack]) -> str:
    names = list(names)
    return ", ".join(_pack_link(n, known) for n in names) if names else "none"


# ---------------------------------------------------------------------------
# Pack and bundle pages
# ---------------------------------------------------------------------------


def _read_yaml(path: Optional[Path]) -> Any:
    if path is None or not path.is_file():
        return None
    return load_unique_yaml(path.read_text(encoding="utf-8"))


def _bundles_selecting(catalog: Catalog, pack: str) -> tuple[list[str], list[str]]:
    default = sorted(b.name for b in catalog.bundles.values() if pack in b.default_packs)
    optional = sorted(b.name for b in catalog.bundles.values() if pack in b.optional_packs)
    return default, optional


def pack_page(pack: Pack, catalog: Catalog) -> str:
    m = pack.manifest
    out = [BANNER.format(source=f"bundles/packs/{pack.name}/pack.yaml"), f"# Pack: {pack.name}", ""]
    out += [_one_line(m["description"]), ""]
    out += _table(
        ["Field", "Value"],
        [
            ["Kind", _code(pack.kind)],
            ["Version", _code(pack.version)],
            ["Needs a credential to publish", "yes" if pack.needs_credentials else "no"],
            ["Okg modules it needs", ", ".join(_code(x) for x in pack.requires_modules) or "none"],
            ["Packs it needs", _list_inline(pack.requires_packs, catalog.packs)],
        ],
    )

    default, optional = _bundles_selecting(catalog, pack.name)
    out += ["## In which bundles", ""]
    link = lambda names: ", ".join(f"[`{n}`](../bundles/{n}.md)" for n in names) or "none"  # noqa: E731
    out += [f"- Default in: {link(default)}", f"- Optional in: {link(optional)}"]
    from archi.bundles.manifest import merged_companions

    for b in sorted(catalog.bundles.values(), key=lambda b: b.name):
        for trigger, companions in sorted(merged_companions(b.name, catalog.bundles).items()):
            if pack.name in companions:
                out += [f"- Comes with {_pack_link(trigger, catalog.packs)} in: {link([b.name])}"]
    out += [""]
    out += [f"Add it to an instance with `archi add {pack.name}`.", ""]

    sources = pack.sources()
    out += ["## Sources", ""]
    if sources:
        out += [f"- `{pack.name}.{name}`" for name in sources] + [""]
    else:
        out += ["This pack has no sources."]
        out += ["Records reach it through okg admission, not through a connector.", ""] if pack.kind == "context" else [""]

    questions = pack.questions()
    out += ["## Questions", ""]
    if questions:
        out += ["`archi init` asks these. Answer one with `--answer " f"{pack.name.replace('-', '_')}_<id>=VALUE`.", ""]
        out += _table(
            ["Id", "Type", "Required", "Default", "Prompt"],
            [
                [
                    _code(q["id"]),
                    _code(q.get("type", "")),
                    "yes" if q.get("required") else "no",
                    _code(q["default"]) if "default" in q else "",
                    _cell(q.get("prompt", "")),
                ]
                for q in questions
            ],
        )
    else:
        out += ["This pack asks no questions.", ""]

    out += ["## Credentials", ""]
    if pack.credentials:
        out += ["The pack reads these environment variables. Only the names are listed; values stay in the instance's `.env`.", ""]
        out += [f"- `{c}`" for c in pack.credentials] + [""]
    else:
        out += ["The manifest names no credential variable.", ""]

    fresh = pack.freshness
    out += ["## Freshness limits", ""]
    if fresh:
        out += ["`archi doctor` compares each source's age with its limit.", ""]
        out += _table(["Source", "Longest acceptable age"], [[_code(k), _code(v["max_staleness"])] for k, v in sorted(fresh.items())])
    else:
        out += ["The pack declares no freshness limit.", ""]

    if pack.link_coverage:
        out += ["## Link coverage targets", ""]
        out += _table(
            ["Name", "From", "Edge", "To", "Direction", "Minimum share", "Severity"],
            [
                [
                    _code(t["name"]),
                    _code(t["from"]),
                    _code(t["edge"]),
                    _code(t["to"]),
                    t.get("direction", "out"),
                    f"{t['min_fraction']:g}",
                    t.get("severity", "warn"),
                ]
                for t in pack.link_coverage
            ],
        )

    inv = _read_yaml(pack.path("invariants")) or {}
    invariants = inv.get("invariants", []) if isinstance(inv, Mapping) else []
    out += ["## Invariants", ""]
    if invariants:
        out += ["The pack owns these checks. They leave with it.", ""]
        out += _table(
            ["Name", "Severity", "What it checks"],
            [[_code(i["name"]), i.get("severity", ""), _cell(i.get("description", ""))] for i in invariants],
        )
    else:
        out += ["The pack declares no invariant.", ""]

    playbook_dir = pack.path("playbooks")
    out += ["## Playbooks", ""]
    playbooks = sorted(p.relative_to(playbook_dir).as_posix() for p in playbook_dir.rglob("*.md")) if playbook_dir and playbook_dir.is_dir() else []
    out += [f"- `{p}`" for p in playbooks] + [""] if playbooks else ["The pack ships no playbook.", ""]

    if pack.live_tools:
        out += ["## Live tools", ""]
        idem = set(pack.idempotent_tools)
        out += [f"- `{t}`" + (" (idempotent)" if t in idem else "") for t in pack.live_tools] + [""]

    if pack.kind == "automation":
        out += _automation_section(pack)
    return "\n".join(out).rstrip() + "\n"


def _automation_section(pack: Pack) -> list[str]:
    a = pack.manifest.get("automation", {})
    out = ["## Automation", ""]
    trigger = a.get("trigger", {})
    gate = a.get("context_gate", {})
    budget = a.get("budget", {})
    out += _table(
        ["Field", "Value"],
        [
            ["Trigger", ", ".join(f"{k} = {_code(v)}" for k, v in trigger.items())],
            ["Context gate", ", ".join(f"{k} = {_code(v)}" for k, v in gate.items()) or "none"],
            ["Playbook", _code(a.get("playbook", ""))],
            ["Budget", ", ".join(f"{k} = {_code(v)}" for k, v in budget.items())],
            ["Level it starts at", _code(a.get("default_level", ""))],
            ["Highest level the pack allows", _code(a.get("max_level", ""))],
        ],
    )
    out += ["The instance sets the level in `archi.yaml`. A bundle can lower the upper bound but not raise it. Every automation starts in shadow mode.", ""]
    path = pack.path("action_classes")
    classes = (_read_yaml(path) or {}).get("action_classes", {}) if path else {}
    out += ["### Action classes", ""]
    out += _table(
        ["Id", "Mediator", "Reversible", "Highest level", "Blast radius"],
        [
            [
                _code(cid),
                _code(c["mediator"]),
                "yes" if c["reversible"] else "no",
                _code(c["max_level"]),
                _cell(c["blast_radius"]),
            ]
            for cid, c in sorted(classes.items())
        ],
    )
    return out


def bundle_page(bundle: Bundle, catalog: Catalog) -> str:
    m = bundle.manifest
    out = [BANNER.format(source=f"bundles/{bundle.name}/bundle.yaml"), f"# Bundle: {bundle.name}", ""]
    out += [_one_line(m["description"]), ""] if m.get("description") else []
    out += _table(
        ["Field", "Value"],
        [
            ["Version", _code(bundle.version)],
            ["Extends", ", ".join(f"[`{b}`]({b}.md)" for b in bundle.extends) or "nothing"],
            ["Okg versions it supports", _code(bundle.okg)],
        ],
    )
    out += ["## Packs", ""]
    out += [f"- Default: {_list_inline(bundle.default_packs, catalog.packs)}"]
    out += [f"- Optional: {_list_inline(bundle.optional_packs, catalog.packs)}"]
    from archi.bundles.manifest import merged_companions

    for trigger, companions in sorted(merged_companions(bundle.name, catalog.bundles).items()):
        out += [f"- With {_list_inline((trigger,), catalog.packs)}, also: "
                f"{_list_inline(companions, catalog.packs)} (opt out with `--without`)"]
    out += [""]
    out += ["Default packs install with the bundle. Add an optional pack with `--with <pack>` at init, or `archi add <pack>` later."]
    if bundle.extends:
        out += ["The bundle also installs the default packs of the bundles it extends."]
    out += ["", "```bash", f"archi init myteam --bundle {bundle.name}", "```", ""]

    if bundle.answers:
        out += ["## Answers the bundle fixes", ""]
        out += _table(["Id", "Value"], [[_code(k), _code(v)] for k, v in sorted(bundle.answers.items())])

    chat = bundle.chat
    if chat:
        out += ["## Chat preset", ""]
        rows = [[_code(k), _code(chat[k])] for k in ("site_name", "default_model") if k in chat]
        out += _table(["Setting", "Value"], rows)
        if chat.get("suggestions"):
            out += ["Suggested questions:", ""] + [f"- {_one_line(s)}" for s in chat["suggestions"]] + [""]

    out += ["## Automation level bounds", ""]
    bounds = bundle.automation_bounds
    if bounds:
        out += _table(["Automation", "Highest level"], [[_code(k), _code(v)] for k, v in sorted(bounds.items())])
    else:
        out += ["The bundle sets no bound. Each automation pack's own limit applies.", ""]
    if m.get("eval"):
        out += ["## Eval set", "", f"The bundle names {_code(m['eval'])} as its eval set.", ""]
    return "\n".join(out).rstrip() + "\n"


def _index_page(catalog: Catalog) -> str:
    out = [BANNER.format(source="bundles/"), "# Bundles and packs in this release", ""]
    out += ["Each page below is generated from the manifest in the repository, so it cannot drift from what ships.", ""]
    out += ["## Bundles", ""]
    out += _table(
        ["Bundle", "Description"],
        [[f"[`{n}`](bundles/{n}.md)", _one_line(b.manifest.get("description", ""))] for n, b in sorted(catalog.bundles.items())],
    )
    out += ["## Packs", ""]
    out += _table(
        ["Pack", "Kind", "Description"],
        [[f"[`{n}`](packs/{n}.md)", p.kind, _one_line(p.manifest["description"])] for n, p in sorted(catalog.packs.items())],
    )
    return "\n".join(out).rstrip() + "\n"


